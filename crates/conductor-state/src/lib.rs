//! Shared serde types and storage for conductor's on-disk state under `~/.config/conductor/`.
//! Used by the `conductor` CLI and by `conductor-deck`.
//!
//! | Type | File |
//! |---|---|
//! | [`Config`] | `config.toml` |
//! | [`RepoRecord`] | `repos/<repo-id>/repo.json` |
//! | [`Task`] | `repos/<repo-id>/tasks/<task-id>/task.json` |
//! | [`Event`] | one line of `tasks/<task-id>/events.jsonl` |
//! | [`Decision`] | `tasks/<task-id>/decisions/<key>.json` |
//!
//! # Conventions
//!
//! - Every key and enum value is `snake_case`.
//! - Top-level JSON files (`task.json`, `repo.json`, `decisions/<key>.json`) carry
//!   `"schema": "conductor-state.v1"` ([`SchemaV1`]). Reading a file with any other marker
//!   fails. Event lines and `config.toml` have no marker.
//! - Optional fields are omitted when unset, never written as `null`.
//! - Unknown fields are ignored on read, so a newer writer can add fields without breaking an
//!   older reader. An unknown event `kind` reads as [`EventPayload::Unknown`].
//! - Timestamps are RFC 3339 in UTC; durations in `config.toml` use jiff's friendly format,
//!   e.g. `"2m"`.
//!
//! # Storage
//!
//! [`Home`] finds the state root (`CONDUCTOR_HOME`, else `~/.config/conductor`) and lays out
//! the paths under it; [`resolve_repo`] gives a repo's id, the same from the main checkout
//! and from any worktree of it; [`Config::load`] reads `config.toml`, where a missing file
//! means the defaults. The writing rules, which avoid any locking:
//!
//! - `events.jsonl` is only appended to, by [`append_event`]: one JSON line of at most
//!   [`MAX_EVENT_LINE`] bytes per `write` with `O_APPEND`, so concurrent appenders never
//!   interleave. Long text fields are cut to [`MAX_TEXT_FIELD`]. [`read_events`] tails it
//!   from a saved offset.
//! - `task.json` has one writer, the `conductor` CLI, through [`write_task_atomic`]: a temp
//!   file, `fsync`, then `rename`. `repo.json` and `decisions/<key>.json` are written the same
//!   way, also only by the CLI, by [`write_repo_record_atomic`] and [`write_decision_atomic`].
//! - The deck writes none of these. It computes each card's [`LiveStatus`] with [`fold`], and
//!   answers a decision by running `conductor decision answer`.
//!
//! # JSON Schema
//!
//! [`SCHEMA_JSON`] is the committed schema for every type, generated by [`json_schema`]. After
//! changing a type, regenerate it with
//! `UPDATE_SCHEMA=1 cargo test -p conductor-state --test schema`.

